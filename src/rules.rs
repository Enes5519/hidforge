//! udev rule generation, validation and lookup.

use crate::devices::{Device, UsbId};
use std::fs;
use std::path::{Path, PathBuf};

pub const RULES_DIR: &str = "/etc/udev/rules.d";
pub const FILE_PREFIX: &str = "70-hidforge-";
/// Prefix used before the project was renamed to hidforge. Still recognised so rules
/// installed by older versions show up and can be updated or removed.
const LEGACY_PREFIX: &str = "70-driver-generator-";
const MAX_RULE_SIZE: usize = 4096;
const SEARCH_DIRS: [&str; 3] = [
    "/etc/udev/rules.d",
    "/run/udev/rules.d",
    "/usr/lib/udev/rules.d",
];

/// Save a rule somewhere without installing it.
pub fn export(path: &Path, content: &str) -> Result<(), String> {
    fs::write(path, content).map_err(|e| format!("{}: {e}", path.display()))
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum AccessMode {
    /// `TAG+="uaccess"`: ACL for the user logged in at the seat. Recommended.
    Uaccess,
    /// `MODE="0660", GROUP="input"`: every member of the `input` group.
    InputGroup,
}

impl AccessMode {
    fn suffix(self) -> &'static str {
        match self {
            AccessMode::Uaccess => r#"TAG+="uaccess""#,
            AccessMode::InputGroup => r#"MODE="0660", GROUP="input""#,
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct RuleOptions {
    pub hidraw: bool,
    pub usb: bool,
    pub mode: AccessMode,
}

impl RuleOptions {
    pub fn default_for(dev: &Device) -> Self {
        Self {
            hidraw: dev.is_hid(),
            usb: !dev.is_hid(),
            mode: AccessMode::Uaccess,
        }
    }

    pub fn is_valid(&self) -> bool {
        self.hidraw || self.usb
    }
}

pub fn file_name(id: &UsbId) -> String {
    name_with_prefix(FILE_PREFIX, id)
}

/// Name an older version (before the rename) would have used for this device.
pub fn legacy_file_name(id: &UsbId) -> String {
    name_with_prefix(LEGACY_PREFIX, id)
}

fn name_with_prefix(prefix: &str, id: &UsbId) -> String {
    format!("{prefix}{:04x}-{:04x}.rules", id.vid, id.pid)
}

/// Parse a file name we generated (current or legacy prefix) back into its id.
pub fn id_from_file_name(name: &str) -> Option<UsbId> {
    [FILE_PREFIX, LEGACY_PREFIX].into_iter().find_map(|prefix| {
        let rest = name.strip_prefix(prefix)?.strip_suffix(".rules")?;
        let (vid, pid) = rest.split_once('-')?;
        let id = UsbId::new(vid, pid)?;
        (name_with_prefix(prefix, &id) == name).then_some(id)
    })
}

fn rule_line(subsystem: &str, id: &UsbId, mode: AccessMode) -> String {
    format!(
        r#"SUBSYSTEM=="{subsystem}", ATTRS{{idVendor}}=="{:04x}", ATTRS{{idProduct}}=="{:04x}", {}"#,
        id.vid,
        id.pid,
        mode.suffix()
    )
}

/// Strip anything that could break out of a comment line.
fn sanitize_comment(s: &str) -> String {
    s.chars()
        .filter(|c| !c.is_control())
        .take(120)
        .collect::<String>()
        .trim()
        .to_string()
}

pub fn generate(dev: &Device, opts: &RuleOptions) -> String {
    let mut out = format!(
        "# Generated by hidforge: {} ({})\n",
        sanitize_comment(&dev.display_name()),
        dev.id
    );
    if opts.hidraw {
        out.push_str(&rule_line("hidraw", &dev.id, opts.mode));
        out.push('\n');
    }
    if opts.usb {
        out.push_str(&rule_line("usb", &dev.id, opts.mode));
        out.push('\n');
    }
    out
}

/// Strict check run by the root helper: the file name must be ours and every non-comment line
/// must be byte-identical to a line `generate` could have produced for that file's VID:PID.
pub fn validate(name: &str, content: &str) -> Result<UsbId, String> {
    let id = id_from_file_name(name).ok_or_else(|| tr!("err.invalid_file_name", name = name))?;
    if content.len() > MAX_RULE_SIZE {
        return Err(tr!("err.rule_too_large"));
    }
    let allowed: Vec<String> = ["hidraw", "usb"]
        .iter()
        .flat_map(|s| [AccessMode::Uaccess, AccessMode::InputGroup].map(|m| rule_line(s, &id, m)))
        .collect();
    let mut rule_count = 0;
    for (n, line) in content.lines().enumerate() {
        if line.is_empty() {
            continue;
        }
        if let Some(comment) = line.strip_prefix('#') {
            if comment.chars().any(char::is_control) {
                return Err(tr!("err.rule_comment_control", line = n + 1));
            }
            continue;
        }
        if !allowed.iter().any(|a| a == line) {
            // Line number only: the helper runs as root, never echo file content.
            return Err(tr!("err.rule_disallowed", line = n + 1));
        }
        rule_count += 1;
    }
    if rule_count == 0 {
        return Err(tr!("err.rule_empty"));
    }
    Ok(id)
}

#[derive(Clone, Debug)]
pub struct InstalledRule {
    pub path: PathBuf,
    pub file_name: String,
    pub id: Option<UsbId>,
    pub content: String,
    /// True when this tool created the file (and can therefore remove it).
    pub ours: bool,
}

/// Rules this tool installed.
pub fn installed() -> Vec<InstalledRule> {
    let mut out: Vec<InstalledRule> = read_rules_dir(Path::new(RULES_DIR))
        .into_iter()
        .filter(|r| r.ours)
        .collect();
    out.sort_by(|a, b| a.file_name.cmp(&b.file_name));
    out
}

/// Every rule file (ours or not, any rules dir) that mentions this VID and PID.
pub fn existing_for(id: &UsbId) -> Vec<InstalledRule> {
    // Compared against lowercased lines, so the patterns are lowercase too.
    let vid = format!(r#"idvendor}}=="{:04x}""#, id.vid);
    let pid = format!(r#"idproduct}}=="{:04x}""#, id.pid);
    SEARCH_DIRS
        .iter()
        .flat_map(|d| read_rules_dir(Path::new(d)))
        .filter(|r| {
            r.content.lines().any(|l| {
                let l = l.to_ascii_lowercase();
                !l.trim_start().starts_with('#') && l.contains(&vid) && l.contains(&pid)
            })
        })
        .collect()
}

fn read_rules_dir(dir: &Path) -> Vec<InstalledRule> {
    let Ok(entries) = fs::read_dir(dir) else {
        return Vec::new();
    };
    entries
        .flatten()
        .filter_map(|e| {
            let file_name = e.file_name().to_str()?.to_string();
            if !file_name.ends_with(".rules") {
                return None;
            }
            let content = fs::read_to_string(e.path()).ok()?;
            let id = id_from_file_name(&file_name);
            Some(InstalledRule {
                ours: id.is_some() && dir == Path::new(RULES_DIR),
                path: e.path(),
                file_name,
                id,
                content,
            })
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn dev(hid: bool) -> Device {
        Device {
            id: UsbId::new("1a2c", "2002").unwrap(),
            vendor: "GamePower".into(),
            product: "EVA 7\n".into(),
            serial: None,
            hidraw_nodes: if hid {
                vec!["/dev/hidraw8".into()]
            } else {
                vec![]
            },
            usb_nodes: vec!["/dev/bus/usb/008/004".into()],
            wine_issues: vec![],
        }
    }

    #[test]
    fn generates_expected_rule() {
        let d = dev(true);
        let rule = generate(&d, &RuleOptions::default_for(&d));
        assert_eq!(
            rule,
            "# Generated by hidforge: GamePower EVA 7 (1a2c:2002)\n\
             SUBSYSTEM==\"hidraw\", ATTRS{idVendor}==\"1a2c\", ATTRS{idProduct}==\"2002\", TAG+=\"uaccess\"\n"
        );
    }

    #[test]
    fn non_hid_defaults_to_usb() {
        let d = dev(false);
        let rule = generate(&d, &RuleOptions::default_for(&d));
        assert!(rule.contains(r#"SUBSYSTEM=="usb""#));
        assert!(!rule.contains("hidraw"));
    }

    #[test]
    fn file_name_round_trip() {
        let id = UsbId::new("1A2C", "2002").unwrap();
        let name = file_name(&id);
        assert_eq!(name, "70-hidforge-1a2c-2002.rules");
        assert_eq!(id_from_file_name(&name), Some(id));
        assert!(id_from_file_name("70-hidforge-1a2c-2002.rules.bak").is_none());
        assert!(id_from_file_name("70-hidforge-../../x-2002.rules").is_none());
        // Rules from before the rename are still ours.
        assert_eq!(legacy_file_name(&id), "70-driver-generator-1a2c-2002.rules");
        assert_eq!(
            id_from_file_name("70-driver-generator-1a2c-2002.rules"),
            Some(id)
        );
        assert!(id_from_file_name("70-driver-generator-../../x-2002.rules").is_none());
        assert!(id_from_file_name("99-other.rules").is_none());
    }

    #[test]
    fn validate_accepts_generated() {
        let d = dev(true);
        for mode in [AccessMode::Uaccess, AccessMode::InputGroup] {
            let opts = RuleOptions {
                hidraw: true,
                usb: true,
                mode,
            };
            let rule = generate(&d, &opts);
            assert!(validate(&file_name(&d.id), &rule).is_ok(), "{rule}");
        }
    }

    #[test]
    fn validate_rejects_tampering() {
        let name = "70-hidforge-1a2c-2002.rules";
        let ok = r#"SUBSYSTEM=="hidraw", ATTRS{idVendor}=="1a2c", ATTRS{idProduct}=="2002", TAG+="uaccess""#;
        // wrong id for file name
        assert!(validate(name, &ok.replace("2002", "2003")).is_err());
        // command execution
        assert!(validate(name, &format!("{ok}, RUN+=\"/bin/sh -c evil\"")).is_err());
        assert!(validate(name, "RUN+=\"/bin/sh\"").is_err());
        // world writable
        assert!(validate(name, &ok.replace(r#"TAG+="uaccess""#, r#"MODE="0666""#)).is_err());
        // only comments
        assert!(validate(name, "# nothing\n").is_err());
        // bad name
        assert!(validate("../../etc/passwd", ok).is_err());
        assert!(validate(name, ok).is_ok());
    }
}
