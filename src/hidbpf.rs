//! HID-BPF report-descriptor fixups, loaded by `udev-hid-bpf`.
//!
//! The program is generated for one exact descriptor: `probe` only accepts a HID interface whose
//! descriptor is byte-identical to the one analysed, so the other interfaces of the same device
//! (and any firmware revision with a different descriptor) are left alone.

use crate::devices::UsbId;
use std::fmt::Write;

pub const BPF_DIR: &str = "/etc/udev-hid-bpf";
/// `udev-hid-bpf` orders files by this numeric prefix; 0010 is the "stable" range.
const FILE_PREFIX: &str = "0010-hidforge__";
/// Prefix used before the project was renamed to hidforge; still recognised for removal.
const LEGACY_PREFIX: &str = "0010-driver-generator__";

/// clang flags for [`generate_source`] output.
pub const CLANG_ARGS: [&str; 6] = ["-O2", "-g", "-target", "bpf", "-fno-builtin", "-Wall"];

/// Object file name, e.g. `0010-hidforge__1d57-fa60-if2.bpf.o`.
pub fn object_name(id: &UsbId, iface: u8) -> String {
    name_with_prefix(FILE_PREFIX, id, iface)
}

fn name_with_prefix(prefix: &str, id: &UsbId, iface: u8) -> String {
    format!("{prefix}{:04x}-{:04x}-if{iface}.bpf.o", id.vid, id.pid)
}

/// Parse a name produced by [`object_name`] (or an older version) back into its parts.
pub fn parse_object_name(name: &str) -> Option<(UsbId, u8)> {
    [FILE_PREFIX, LEGACY_PREFIX].into_iter().find_map(|prefix| {
        let rest = name.strip_prefix(prefix)?.strip_suffix(".bpf.o")?;
        let mut it = rest.splitn(3, '-');
        let (vid, pid, iface) = (it.next()?, it.next()?, it.next()?);
        let iface: u8 = iface.strip_prefix("if")?.parse().ok()?;
        let id = UsbId::new(vid, pid)?;
        (name_with_prefix(prefix, &id, iface) == name).then_some((id, iface))
    })
}

/// udev rule `udev-hid-bpf install` writes next to the object.
pub fn rule_path(object: &str) -> std::path::PathBuf {
    let stem = object.strip_suffix(".bpf.o").unwrap_or(object);
    std::path::Path::new("/etc/udev/rules.d").join(format!("99-hid-bpf-{stem}.rules"))
}

/// Our fixups installed for a device.
pub fn installed_for(id: &UsbId) -> Vec<String> {
    let Ok(entries) = std::fs::read_dir(BPF_DIR) else {
        return Vec::new();
    };
    let mut out: Vec<String> = entries
        .flatten()
        .filter_map(|e| e.file_name().into_string().ok())
        .filter(|n| parse_object_name(n).is_some_and(|(i, _)| &i == id))
        .collect();
    out.sort();
    out
}

fn hex_array(bytes: &[u8]) -> String {
    let mut s = String::new();
    for (i, chunk) in bytes.chunks(16).enumerate() {
        if i > 0 {
            s.push('\n');
        }
        s.push('\t');
        for b in chunk {
            let _ = write!(s, "0x{b:02x}, ");
        }
    }
    s
}

/// Kernel limit for a report descriptor, and the buffer size the fixup writes into.
pub const MAX_DESCRIPTOR_SIZE: usize = 4096;

/// C source for a fixup that replaces `original` with `fixed`. Only ever called with data
/// derived from sysfs by our own analyser; nothing user-supplied reaches the template.
/// Fails when `fixed` would not fit the kernel's descriptor buffer (the verifier would reject
/// the program at every plug-in, after it was already installed).
pub fn generate_source(id: &UsbId, original: &[u8], fixed: &[u8]) -> Result<String, String> {
    if fixed.len() > MAX_DESCRIPTOR_SIZE {
        return Err(tr!(
            "err.descriptor_too_large",
            size = fixed.len(),
            max = MAX_DESCRIPTOR_SIZE
        ));
    }
    let (vid, pid) = (id.vid, id.pid);
    Ok(format!(
        r#"// SPDX-License-Identifier: GPL-2.0-only
// Generated by hidforge for {id}.
// Repeats globals inherited across top-level collections so Wine sizes reports correctly.

#include <linux/types.h>
#include <bpf/bpf_helpers.h>
#include <bpf/bpf_tracing.h>

#define BUS_USB 0x03
#define HID_GROUP_GENERIC 0x0001
#define HID_MAX_DESCRIPTOR_SIZE {MAX_DESCRIPTOR_SIZE}

struct hid_device;
struct hid_bpf_ctx {{
	struct hid_device *hid;
	__u32 allocated_size;
	union {{
		__s32 retval;
		__s32 size;
	}};
}} __attribute__((preserve_access_index));

struct hid_bpf_ops {{
	int hid_id;
	__u32 flags;
	int (*hid_rdesc_fixup)(struct hid_bpf_ctx *ctx);
}} __attribute__((preserve_access_index));

struct hid_bpf_probe_args {{
	unsigned int hid;
	unsigned int rdesc_size;
	unsigned char rdesc[HID_MAX_DESCRIPTOR_SIZE];
	int retval;
}};

extern __u8 *hid_bpf_get_data(struct hid_bpf_ctx *ctx, unsigned int offset,
			      const __u64 sz) __ksym;

#define HID_DEVICE(b, g, ven, prod) \
	struct {{ __uint(name, 0); __uint(bus, (b)); __uint(group, (g)); \
		 __uint(vid, (ven)); __uint(pid, (prod)); }} _entry_##ven##_##prod
#define HID_BPF_CONFIG(...) union {{ __VA_ARGS__; }} _device_ids SEC(".hid_bpf_config")

HID_BPF_CONFIG(HID_DEVICE(BUS_USB, HID_GROUP_GENERIC, 0x{vid:04x}, 0x{pid:04x}));

#define ORIG_SIZE {orig_size}
#define FIXED_SIZE {fixed_size}

static const __u8 original[ORIG_SIZE] = {{
{orig}
}};

static const __u8 fixed[FIXED_SIZE] = {{
{fixed}
}};

SEC("struct_ops/hid_rdesc_fixup")
int BPF_PROG(dg_rdesc_fixup, struct hid_bpf_ctx *hctx)
{{
	__u8 *data = hid_bpf_get_data(hctx, 0, HID_MAX_DESCRIPTOR_SIZE);

	if (!data)
		return 0;
	/* Plain loop; must be built with -fno-builtin so clang does not turn it into a
	 * memcpy call (BPF has no libc). */
	for (int i = 0; i < FIXED_SIZE; i++)
		data[i] = fixed[i];
	return FIXED_SIZE;
}}

SEC(".struct_ops.link")
struct hid_bpf_ops hidforge_fixup = {{
	.hid_rdesc_fixup = (void *)dg_rdesc_fixup,
}};

SEC("syscall")
int probe(struct hid_bpf_probe_args *ctx)
{{
	ctx->retval = -22;
	if (ctx->rdesc_size != ORIG_SIZE)
		return 0;
	for (int i = 0; i < ORIG_SIZE; i++)
		if (ctx->rdesc[i] != original[i])
			return 0;
	ctx->retval = 0;
	return 0;
}}

char _license[] SEC("license") = "GPL";
"#,
        orig_size = original.len(),
        fixed_size = fixed.len(),
        orig = hex_array(original),
        fixed = hex_array(fixed),
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn object_name_round_trip() {
        let id = UsbId::new("1D57", "fa60").unwrap();
        let name = object_name(&id, 2);
        assert_eq!(name, "0010-hidforge__1d57-fa60-if2.bpf.o");
        assert_eq!(parse_object_name(&name), Some((id, 2)));
        assert!(parse_object_name("0010-hidforge__1d57-fa60-if2.bpf.o.bak").is_none());
        assert!(parse_object_name("0010-hidforge__../x-fa60-if2.bpf.o").is_none());
        // Fixups from before the rename are still ours.
        assert_eq!(
            parse_object_name("0010-driver-generator__1d57-fa60-if2.bpf.o"),
            Some((id, 2))
        );
        assert!(parse_object_name("0010-driver-generator__../x-fa60-if2.bpf.o").is_none());
        assert!(parse_object_name("0010-Rapoo__M50-Plus-Silent.bpf.o").is_none());
    }

    #[test]
    fn rejects_fixed_descriptor_over_kernel_limit() {
        let id = UsbId::new("1234", "5678").unwrap();
        let orig = vec![0u8; MAX_DESCRIPTOR_SIZE - 10];
        let src = generate_source(&id, &orig, &vec![0u8; MAX_DESCRIPTOR_SIZE]).unwrap();
        assert!(src.contains("0x1234, 0x5678"));
        assert!(src.contains("#define HID_MAX_DESCRIPTOR_SIZE 4096"));
        assert!(generate_source(&id, &orig, &vec![0u8; MAX_DESCRIPTOR_SIZE + 1]).is_err());
    }
}
